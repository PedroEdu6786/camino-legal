import test from 'node:test';
import assert from 'node:assert/strict';
import { acquisitionCategories, EVENT_NAMES, PendingMeasurements, pageIdentity, serviceFromDestination, sanitizeParams } from '../app/lib/measurement/contracts.ts';
import { attributionContext, beginPage, configureProviders, getConsent, getConsentSnapshot, markProviderReady, metaBrowserContextSafe, setConsent, setServerConsentSync, trackEvent } from '../app/lib/analytics.ts';

const uuid = () => crypto.randomUUID();
test('canonical route classification never echoes unknown path or query values', () => {
  for (const path of ['/', '/servicios', '/cotizaciones', '/nosotros', '/preguntas', '/contacto']) assert.notEqual(pageIdentity(path).page_type, 'unknown');
  assert.equal(pageIdentity('/servicios/registro-de-marca').service_id, 'registro-de-marca');
  assert.deepEqual(pageIdentity('/private/alice@example.com'), { page_path: '/unknown', page_type: 'unknown', service_id: 'unspecified' });
  assert.equal(pageIdentity('/cotizaciones?email=alice@example.com').page_path, '/unknown');
});
test('internal service and quotation destinations infer only registered service context', () => {
  assert.equal(serviceFromDestination('/servicios/consultoria-legal'), 'consultoria-legal');
  assert.equal(serviceFromDestination('/cotizaciones', '?servicio=contratos-y-convenios&email=private@example.com'), 'contratos-y-convenios');
  assert.equal(serviceFromDestination('/cotizaciones', '?servicio=private@example.com'), 'unspecified');
  assert.equal(serviceFromDestination('/contacto', '?servicio=registro-de-marca'), 'unspecified');
  assert.deepEqual(sanitizeParams({ network: 'instagram', destination_id: 'instagram', destination_kind: 'social' }), { network: 'instagram', destination_id: 'instagram', destination_kind: 'social' });
});
test('field enums exclude personal strings, unregistered IDs, and arbitrary content', () => {
  const safe = sanitizeParams({ name: 'Alice', email: 'alice@example.com', source_surface: 'Alice', action_id: 'Alice', campaign: 'private', form_id: 'contact', service_id: 'registro-de-marca', content_id: 'quote_payment_schedule', previous_value: 'alice@example.com', form_instance_id: '529992505160', message: 'private case' });
  assert.deepEqual(safe, { form_id: 'contact', service_id: 'registro-de-marca', content_id: 'quote_payment_schedule' });
  assert.equal(sanitizeParams({ previous_value: 'contratos-y-convenios' }).previous_value, 'contratos-y-convenios');
});
test('custom quote nulls remain null and bounded quote settings reject out-of-range data', () => {
  assert.deepEqual(sanitizeParams({ estimated_total_minor: null, classes: 11, payment_count: 4, ownership_rules: false, currency: 'MXN', price_kind: 'estimate' }), { estimated_total_minor: null, ownership_rules: false, currency: 'MXN', price_kind: 'estimate' });
});
test('acquisition categories never preserve arbitrary campaign or referrer content', () => {
  assert.deepEqual(acquisitionCategories('?utm_source=instagram&utm_medium=paid_social&utm_campaign=trademark', ''), { session_source: 'instagram', session_medium: 'paid_social', session_campaign: 'trademark' });
  const safe = acquisitionCategories('?utm_source=alice@example.com&utm_medium=private-case&utm_campaign=brand-name', 'https://example.com/?email=alice@example.com');
  assert.deepEqual(safe, { session_source: 'other', session_medium: 'other', session_campaign: 'other' });
  assert.equal(acquisitionCategories('', 'https://www.google.com/search?q=private').session_medium, 'organic');
});
test('eligible buffer is bounded, coalesces identity per destination, and expires without replay', () => {
  const queue = new PendingMeasurements();
  const record = { name: 'page_view', id: uuid(), time: 0, page: pageIdentity('/'), pageViewId: uuid(), params: {} };
  queue.add(record, 'ga4', 0); queue.add(record, 'ga4', 0);
  assert.equal(queue.size, 1);
  for (let i = 0; i < 70; i++) queue.add({ ...record, id: uuid() }, 'ga4', 0);
  assert.equal(queue.size, 50);
  assert.equal(queue.take('meta', 1).length, 0);
  assert.equal(queue.take('ga4', 30_000).length, 0);
  queue.add({ ...record, time: 40_000 }, 'meta', 40_000); queue.clear(); assert.equal(queue.size, 0);
});
test('consent, readiness, conversion ownership, and revocation remain observational', async () => {
  const windowTarget = new EventTarget();
  const calls = [];
  const pixel = [];
  const stored = new Map();
  Object.assign(windowTarget, { location: new URL('https://caminolegal.com.mx/contacto'), gtag: (...args) => calls.push(args), fbq: (...args) => pixel.push(args) });
  globalThis.window = windowTarget;
  globalThis.document = { referrer: '' };
  globalThis.localStorage = { getItem: key => stored.get(key) ?? null, setItem: (key, value) => stored.set(key, value) };
  configureProviders({ ga4: true, meta: true });
  beginPage('/contacto');
  trackEvent('email_click', { source_surface: 'contact' });
  assert.equal(calls.filter(args => args[0] === 'event').length, 0);
  assert.equal(pixel.filter(args => args[0] === 'track').length, 0);
  setConsent('granted'); beginPage('/contacto');
  assert.equal(calls.filter(args => args[0] === 'event').length, 0, 'eligible page waits for readiness');
  markProviderReady('ga4'); markProviderReady('meta'); markProviderReady('ga4'); beginPage('/contacto');
  assert.equal(calls.filter(args => args[1] === 'page_view').length, 1, 'ready callbacks do not create page views');
  const firstView = calls.find(args => args[1] === 'page_view')[2].page_view_id;
  const firstConsentVersion = getConsentSnapshot().version;
  setConsent('granted'); beginPage('/contacto');
  assert.equal(getConsentSnapshot().version, firstConsentVersion, 'reconfirming the current preference does not create an epoch');
  assert.equal(calls.filter(args => args[1] === 'page_view').length, 1, 'same preference cannot duplicate page views');
  const outcome = uuid();
  trackEvent('lead_submitted', { form_id: 'trademark_evaluation', email: 'private@example.com' }, { eventId: outcome });
  trackEvent('lead_submitted', { form_id: 'trademark_evaluation' }, { eventId: outcome });
  assert.equal(calls.filter(args => args[1] === 'lead_submitted').length, 1);
  assert.equal(pixel.filter(args => args[1] === 'Lead').length, 1);
  assert.equal(pixel.find(args => args[1] === 'Lead')[3].eventID, outcome);
  assert.ok(!JSON.stringify(calls).includes('private@example.com'));
  setConsent('denied');
  const count = calls.filter(args => args[0] === 'event').length;
  trackEvent('cta_click', { action_id: 'nav.contact' });
  markProviderReady('ga4');
  assert.equal(calls.filter(args => args[0] === 'event').length, count);
  setConsent('granted'); beginPage('/contacto'); markProviderReady('meta');
  assert.equal(calls.filter(args => args[1] === 'cta_click').length, 0, 'denied actions never replay');
  assert.equal(calls.filter(args => args[1] === 'page_view').length, 2, 'regrant begins current-page eligibility');
  assert.notEqual(calls.filter(args => args[1] === 'page_view')[1][2].page_view_id, firstView, 'new consent eligibility has its own view and exposure denominator');
  localStorage.setItem = () => { throw new Error('blocked storage'); };
  setConsent('denied'); assert.equal(getConsent(), 'denied');
  setConsent('granted'); assert.equal(getConsent(), 'granted');
  let synchronized;
  setServerConsentSync(async (status, version) => { synchronized = { status, version }; return true; });
  await new Promise(resolve => setTimeout(resolve, 0));
  assert.equal(synchronized.version, getConsentSnapshot().version);
  assert.equal(getConsentSnapshot().serverAcknowledged, true);
  window.location = new URL('https://caminolegal.com.mx/cotizaciones?servicio=registro-de-marca');
  assert.equal(metaBrowserContextSafe(), false, 'Pixel implicit URL cannot leak query');
  beginPage('/cotizaciones');
  const pixelCount = pixel.filter(args => args[0] === 'track').length;
  trackEvent('whatsapp_click', { source_surface: 'evaluation_modal' });
  assert.equal(pixel.filter(args => args[0] === 'track').length, pixelCount);
  assert.ok(calls.filter(args => args[0] === 'event').every(args => !args[2].page_location.includes('?')));
  window.location = new URL('https://caminolegal.com.mx/'); document.referrer = 'https://example.com/?email=private@example.com';
  assert.equal(metaBrowserContextSafe(), false);
  assert.equal(EVENT_NAMES.includes('contact_form_submit'), false, 'legacy success cannot double count new conversion');
  window.location = new URL('https://caminolegal.com.mx/servicios/registro-de-marca');
  beginPage(window.location.pathname);
  const send = window.gtag;
  window.gtag = undefined;
  trackEvent('cta_click', { action_id: 'service.quote.registro-de-marca' });
  window.location = new URL('https://caminolegal.com.mx/contacto');
  beginPage(window.location.pathname);
  window.gtag = send;
  markProviderReady('ga4');
  const originalContext = calls.find(args => args[1] === 'cta_click' && args[2].action_id === 'service.quote.registro-de-marca');
  assert.ok(originalContext[2].page_location.endsWith('/servicios/registro-de-marca'), 'buffered events retain their original canonical page');
  window.location = new URL('https://caminolegal.com.mx/servicios');
  beginPage(window.location.pathname, true);
  trackEvent('service_select', { service_id: 'consultoria-legal', service_context: 'explicit' });
  window.location = new URL('https://caminolegal.com.mx/contacto');
  beginPage(window.location.pathname);
  assert.deepEqual(attributionContext(), { service_id: 'consultoria-legal', service_context: 'referral' });
  setConsent('denied');
  assert.deepEqual(attributionContext(), { service_id: 'unspecified', service_context: 'unspecified' });
  setConsent('granted');
  window.location = new URL('https://caminolegal.com.mx/cotizaciones');
  beginPage(window.location.pathname);
  trackEvent('quote_view', { service_id: 'registro-de-marca', service_context: 'displayed_default' });
  assert.equal(attributionContext().service_id, 'unspecified', 'passive default quote is not expressed service interest');
  trackEvent('quote_change', { service_id: 'contratos-y-convenios', service_context: 'explicit', control_id: 'service' });
  beginPage(window.location.pathname);
  assert.equal(attributionContext().service_id, 'contratos-y-convenios', 'same-page refresh does not overwrite a local selection');
  window.location = new URL('https://caminolegal.com.mx/contacto');
  beginPage(window.location.pathname);
  assert.deepEqual(attributionContext(), { service_id: 'contratos-y-convenios', service_context: 'referral' });
  window.location = new URL('https://caminolegal.com.mx/cotizaciones');
  beginPage(window.location.pathname);
  trackEvent('quote_change', { service_id: 'consultoria-legal', service_context: 'explicit', control_id: 'service' });
  setConsent('denied'); setConsent('granted');
  assert.equal(attributionContext().service_id, 'unspecified', 'revocation clears local-selection attribution even on the same quotation page');
  const beforeAdmin = calls.filter(args => args[0] === 'event').length;
  const beforeMeta = pixel.filter(args => args[0] === 'track').length;
  window.gtag = undefined;
  trackEvent('cta_click', { action_id: 'quote.evaluation' });
  window.location = new URL('https://caminolegal.com.mx/admin/analitica');
  assert.equal(beginPage(window.location.pathname), '');
  window.gtag = send;
  markProviderReady('ga4'); markProviderReady('meta');
  trackEvent('page_view'); trackEvent('whatsapp_click');
  assert.equal(calls.filter(args => args[0] === 'event').length, beforeAdmin, 'dashboard creation and queued public events are suppressed');
  assert.equal(pixel.filter(args => args[0] === 'track').length, beforeMeta);
  window.location = new URL('https://caminolegal.com.mx/contacto');
  configureProviders({ ga4: true, meta: true });
  beginPage(window.location.pathname); markProviderReady('ga4');
  assert.equal(calls.filter(args => args[0] === 'event').length, beforeAdmin + 1, 'return to public starts a fresh page without replay');

});
